def get_case(key: str, rate: float = 0.10) -> Scenario:
    """按编号获取单个案例。

    Parameters
    ----------
    key : str
        案例编号，如 ``"CASE-3"``。
    rate : float
        基准折现率。

    Returns
    -------
    Scenario

    Raises
    ------
    KeyError
        编号不存在时。
    """
    mapping: Dict[str, Scenario] = {s.key: s for s in all_cases(rate)}
    normalized = key.strip().upper()
    if normalized not in mapping:
        raise KeyError(f"未找到案例 {key}，可选：{sorted(mapping)}")
    return mapping[normalized]
