# CASE-4：非常规现金流与多重 IRR
# ======================================================================
def case_4_unconventional_cash_flow(rate: float = 0.10) -> Scenario:
    """CASE-4 非常规现金流与多重 IRR 检验。

    **情境**：检验模型在"现金流多次变号"情形下的数值稳健性。

    * **UNC-A 矿山开发项目**：投资 2000 万元，第 1 年现金流 5400 万元，
      第 2 年支付生态治理支出 3520 万元（现金流为负）。
      方程：`-2000 + 5400/(1+r) - 3520/(1+r)² = 0`
      → 存在 **两个 IRR：10% 与 60%**。
    * **UNC-B 化工装置退役治理项目**：投资 2000 万元，现金流 4600 / −2625 万元，
      → 两个 IRR：**5% 与 25%**。

    **核心教学点 —— IRR 失效的三个直接证据**：

    1. **多解**：同一项目存在两个 IRR，无法回答"项目报酬率是多少"；
    2. **NPV 与折现率非单调**（反直觉）：UNC-A 的 NPV 在 10%~60% 区间内
       **先升后降**，在 r ≈ 30.4% 处达到最大值 +71.01 万元。
       即"**折现率上升，NPV 反而变大**"，与常规项目的单调递减规律完全相反；
    3. **结论翻转**：资本成本 10% 时 UNC-A 的 NPV 恰为 0（因为 10% 正是
       其中一个 IRR），但资本成本升到 30% 时 NPV 变为 **+71 万元**。
       若按 IRR = 10% 判断，会误认为"资本成本一旦高于 10% 项目即不可行"，
       与实际完全相反。

    **教学结论**：
    1. 非常规现金流下 IRR 失效，**必须以 NPV 为唯一判据**；
    2. 判定可行性时不能对多重 IRR 项目套用 `IRR > r` 规则
       （本系统已在 :meth:`src.models.Evaluation.build` 中对此做特殊处理）；
    3. 应改用 **MIRR（修正内部收益率）**，MIRR 恒唯一，可给出稳定判据。

    附对照项目 **UNC-C（常规现金流）**：验证常规情形下 IRR 唯一，
    且 NPV 随折现率单调递减。
    """
    return Scenario(
        key="CASE-4",
        name="非常规现金流与多重 IRR 检验",
        teaching_point="现金流多次变号导致 IRR 多解；NPV 与折现率非单调（折现率升高 NPV 反而上升）；"
                       "多重 IRR 项目须以 NPV 为唯一判据并辅以 MIRR",
        discount_rate=rate,
        projects=[
            Project(
                code="UNC-A",
                name="矿山开发项目（含生态治理支出）",
                industry="采掘业",
                initial_investment=2000.0,
                cash_flows=[5400.0, -3520.0],
                risk_level="高",
                description="矿山开采项目，第 1 年投产获取现金 5400 万元，"
                            "第 2 年按监管要求支付生态修复治理支出 3520 万元。"
                            "现金流发生两次符号变化（- → + → -），IRR 存在双解（10% 与 60%）；"
                            "NPV 随折现率呈先升后降的非单调变化，"
                            "在 r≈30.4% 处取最大值 +71.01 万元。",
            ),
            Project(
                code="UNC-B",
                name="化工装置退役治理项目",
                industry="化工环保",
                initial_investment=2000.0,
                cash_flows=[4600.0, -2625.0],
                risk_level="高",
                description="化工装置退役及场地治理项目，第 1 年回收资产残值 4600 万元，"
                            "第 2 年发生拆解与污染治理支出 2625 万元，"
                            "IRR 存在双解（5% 与 25%）。",
            ),
            Project(
                code="UNC-C",
                name="常规现金流对照项目",
                industry="设备投资",
                initial_investment=1500.0,
                cash_flows=[600.0, 600.0, 600.0],
                risk_level="中",
                description="常规现金流对照项目，仅有 1 次符号变化，"
                            "用于验证 IRR 的唯一性（本例 IRR = 9.70%，低于 10% 资本成本，不可行），"
                            "同时展示 NPV 随折现率单调递减的常规规律。",
            ),
        ],
    )


